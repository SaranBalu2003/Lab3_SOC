#!/usr/bin/env python3
"""Independent Fraction oracle; standard-library Python only, deterministic inputs."""
from fractions import Fraction
from pathlib import Path
import json
import struct

CAPACITY = 128

def next_u32(s):
    return (s * 1664525 + 1013904223) & 0xffffffff

def fill(blocks, mode, seed):
    x = [[0x3c00, [0] * 32] for _ in range(CAPACITY)]
    y = [[0x3c00, [0] * 32] for _ in range(CAPACITY)]
    state = seed
    for b in range(CAPACITY):
        if mode == 0:
            state = next_u32(state)
            x[b][0] = state % 0x7c00 | ((state >> 16) & 0x8000)
            state = next_u32(state)
            y[b][0] = state % 0x7c00 | ((state >> 16) & 0x8000)
            for j in range(32):
                state = next_u32(state); x[b][1][j] = (state >> 24) - 128
                state = next_u32(state); y[b][1][j] = (state >> 24) - 128
        elif mode in (1, 2, 5, 7, 8):
            if mode in (2, 7, 8): x[b][0] = y[b][0] = 0x7bff
            if mode == 5: x[b][0] = y[b][0] = 1
            v = -128 if mode in (2, 7, 8) else 1
            x[b][1] = [v] * 32
            y[b][1] = [127 if mode == 8 else v] * 32
            if mode == 7 and b < blocks: x[b][1] = [0] * 32
    if mode in (3, 4):
        for b in (0, 2):
            x[b][0] = y[b][0] = 0x4c00 if mode == 3 else 0x7bff
            if mode == 4 and b == 2: x[b][0] |= 0x8000
            x[b][1] = [-128 if mode == 4 else (64 if b == 0 else -64)] * 32
            y[b][1] = [-128 if mode == 4 else 64] * 32
        x[1][1][0] = y[1][1][0] = 1
        if mode == 4: x[1][0] = y[1][0] = 1
    if mode == 6 and blocks:
        x[blocks - 1][1][31] = -128; y[blocks - 1][1][31] = 127
    return x, y

def half_fraction(h):
    e, f = (h >> 10) & 31, h & 1023
    assert e != 31
    v = Fraction(f, 1 << 24) if e == 0 else Fraction(1024 + f) * Fraction(2) ** (e - 25)
    return -v if h & 0x8000 else v

def exact_bits(v):
    """Round exact finite Fraction to binary32, ties to even; all nonzero cases normal."""
    sign = 0x80000000 if v < 0 else 0
    v = abs(v)
    if not v: return 0
    scaled = v * (1 << 48)
    assert scaled.denominator == 1
    a = scaled.numerator
    k = a.bit_length() - 1
    exponent = k - 48
    if k > 23:
        shift = k - 23
        sig, rem = divmod(a, 1 << shift)
        half = 1 << (shift - 1)
        if rem > half or (rem == half and sig & 1): sig += 1
        if sig == 1 << 24: sig >>= 1; exponent += 1
    else:
        sig = a << (23 - k)
    assert -126 <= exponent <= 127
    return sign | ((exponent + 127) << 23) | (sig & 0x7fffff)

def f32(v):
    return struct.unpack('<f', struct.pack('<f', float(v)))[0]

def bits(v):
    return struct.unpack('<I', struct.pack('<f', v))[0]

def evaluate(blocks, mode, seed):
    x, y = fill(blocks, mode, seed)
    exact = Fraction(0)
    fp32 = 0.0
    for b in range(blocks):
        dx, dy = half_fraction(x[b][0]), half_fraction(y[b][0])
        # Reference is expressed as independent dequantized element products.
        exact += sum((dx * qx) * (dy * qy) for qx, qy in zip(x[b][1], y[b][1]))
        isum = sum(qx * qy for qx, qy in zip(x[b][1], y[b][1]))
        fp32 = f32(fp32 + f32(f32(isum) * f32(f32(dx) * f32(dy))))
    return exact_bits(exact), bits(fp32)

def all_cases():
    lengths = (0, 1, 2, 3, 8, 32, 64, 127, 128)
    cases = []
    for mode, prefix in ((1, 'ones'), (2, 'max_positive'), (5, 'min_subnormal'), (6, 'last_element'), (7, 'ignore_tail'), (8, 'max_negative')):
        for n in lengths: cases.append((f'{prefix}_{n}', n, mode, 0))
    for mode, prefix in ((3, 'fp32_cancellation'), (4, 'extreme_cancellation')):
        for n in (3, 4, 128): cases.append((f'{prefix}_{n}', n, mode, 0))
    for i in range(350):
        n = (1, 2, 3, 8, 32, 64, 128)[i % 7]
        cases.append((f'random_{i:03d}_{n}', n, 0, (0x12345678 + i * 0x9e3779b9) & 0xffffffff))
    return cases

def main():
    root = Path(__file__).resolve().parent
    rows = []
    for name, n, mode, seed in all_cases():
        expected, scalar = evaluate(n, mode, seed)
        rows.append((name, n, mode, seed, expected, scalar))
    header = ['// Generated by generate_cases.py; independent exact Fraction oracle.', '#ifndef LAB3_GOLDEN_CASES_H', '#define LAB3_GOLDEN_CASES_H', '#include "fixtures.h"', 'static const fixtures::Case golden_cases[] = {']
    for name, n, mode, seed, expected, scalar in rows:
        header.append(f'    {{"{name}", {n}u, {mode}u, 0x{seed:08x}u, 0x{expected:08x}u, 0x{scalar:08x}u}},')
    header += ['};', '#endif', '']
    (root / 'golden_cases.h').write_text('\n'.join(header))
    differences = sum(e != f for _, _, _, _, e, f in rows)
    summary = {'extended_cases': len(rows), 'original_cases': 27, 'combined_cases': len(rows) + 27, 'capacity_blocks': 128, 'random_cases': 350, 'exact_vs_sequential_fp32_differences': differences, 'vitis_validation': 'NOT RUN'}
    (root / 'oracle_summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))

if __name__ == '__main__':
    main()
